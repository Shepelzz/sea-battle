// ГЛАВНОЕ ПРАВИЛО ЛОКАЛИЗАЦИИ: в одной партии сидят игроки с РАЗНЫМИ языками,
// а сервер один. Значит сервер НЕ шлёт готовых фраз — только ключи и числа,
// текст рисует клиент своим словарём (public/locales/*.json). События боя
// (pushEvent) с самого начала структурные, так что журнал переводится даром.

export const LANGS = ['uk', 'ru', 'en'];

// Язык-ЭТАЛОН: на нём написаны исходные строки (и текст в самой разметке). В него падаем,
// если ключа нет в выбранном словаре — лучше показать русскую фразу, чем голый ключ.
// На практике не срабатывает: полноту словарей стережёт test-i18n.mjs.
export const SOURCE_LANG = 'ru';

// Язык по умолчанию: гостю, чей Accept-Language ничего не подсказал, показываем украинский.
export const DEFAULT_LANG = 'uk';

export const LANG_COOKIE = 'sb_lang';
export const LANG_TTL_MS = 365 * 24 * 60 * 60 * 1000; // год

export const isLang = l => LANGS.includes(l);

// 'uk-UA' / 'ru_RU' / ' EN ' → 'uk' / 'ru' / 'en'; чужое или мусор → null.
export function normLang(raw) {
  const base = String(raw || '').trim().toLowerCase().split(/[-_;]/)[0];
  return isLang(base) ? base : null;
}

// Какой язык показать. ПРОФИЛЬ > КУКА > ДЕФОЛТ. И всё — больше ничего.
//
// Профиль главнее куки намеренно: залогинился со своего аккаунта — получил СВОЙ язык,
// а не тот, что остался в браузере от чужого/гостевого сеанса на этом устройстве.
//
// ⚠ Accept-Language НЕ смотрим сознательно. Он казался вежливым («уважаем язык браузера»),
// но ломал главное правило: в инкогнито куки нет, браузер шлёт ru-RU — и человек вместо
// украинского получал русский. В Украине русская локаль браузера — обычное дело, так что
// заголовок отправлял бы на русский как раз тех, для кого украинский и ставили дефолтом.
// Не выбирал язык — видишь дефолтный; выбрал переключателем — он запомнится в куке/профиле.
export function pickLang({ profile, cookie } = {}) {
  return normLang(profile) || normLang(cookie) || DEFAULT_LANG;
}

// ─── ЯЗЫК В АДРЕСЕ ────────────────────────────────────────────────────────────
// У каждого языка свой URL: /uk/, /ru/game/xxx, /en/. Иначе поисковик видит только одну
// версию сайта — краулер приходит без куки и профиля, и две трети перевода для него
// просто не существует.
//
// ⚠ АДРЕС ГЛАВНЕЕ ПРОФИЛЯ. Если /en/ показать по-русски (потому что так в профиле), то
// canonical начнёт врать, а страница — спорить сама с собой. Профиль решает только одно:
// куда увести с ГОЛОГО адреса без префикса.

// '/ru/game/x' → { lang: 'ru', rest: '/game/x' }; без префикса → { lang: null, rest: путь }.
export function langFromPath(pathname) {
  const m = /^\/([A-Za-z]{2})(?=\/|$)(.*)$/.exec(String(pathname || '/'));
  const lang = m && normLang(m[1]);
  return lang ? { lang, rest: m[2] || '/' } : { lang: null, rest: String(pathname || '/') || '/' };
}

// Приклеить язык к пути: withLang('ru', '/game/x') → '/ru/game/x'. Уже приклеенный — заменит.
// Корень отдаём со слэшем ('/ru/'), глубже — без хвостового ('/ru/game/x'): у canonical
// должна быть ОДНА форма адреса, иначе поисковик посчитает '/ru' и '/ru/' за разные страницы.
export function withLang(lang, pathname = '/') {
  const code = normLang(lang) || DEFAULT_LANG;
  const { rest } = langFromPath(pathname);
  return rest === '/' ? `/${code}/` : `/${code}${rest}`;
}

// Путь без языка — им ключуется «одна и та же страница на разных языках».
export const stripLang = pathname => langFromPath(pathname).rest;

// Адреса всех языковых версий этой же страницы — для hreflang и карты сайта.
// x-default ведёт на язык по умолчанию: он же стоит на голом адресе после редиректа.
export function langAlternates(pathname = '/') {
  const rest = stripLang(pathname);
  return [
    ...LANGS.map(code => ({ hreflang: code, path: withLang(code, rest) })),
    { hreflang: 'x-default', path: withLang(DEFAULT_LANG, rest) }
  ];
}

// Кука языка — НЕ httpOnly: клиент читает её сам, когда страницу отдал не наш рендер
// (например статикой из кэша). Ничего секретного в ней нет.
export function buildLangCookie(lang, { secure = false, ttlMs = LANG_TTL_MS } = {}) {
  const p = [`${LANG_COOKIE}=${lang}`, 'SameSite=Lax', 'Path=/', `Max-Age=${Math.floor(ttlMs / 1000)}`];
  if (secure) p.push('Secure');
  return p.join('; ');
}
