// ─── 🌬 ВЕТЕР — во ВСЕХ режимах ───────────────────────────────────────────────
// Дальность/скорость хода зависит от направления: по ветру дальше/быстрее, против — меньше.
// Множитель: ×(1 + WIND_STRENGTH·сила·cos(курс − направление ветра)) → каплевидный контур хода.
// Пошаговые партии: ветер живёт в game.wind и меняется МЕЖДУ ходами (advanceTurn) — в свой ход
// он стабилен, планировать можно. Реалтайм: тот же game.wind крутит тик (rt.js).
export const WIND_STRENGTH = 0.35;      // сила влияния: до ±35% дальности/скорости
export const WIND_TURN_STEP = 0.3;      // рад/ход — доворот к целевому направлению (пошагово)
export const WIND_STR_STEP = 0.1;       // изменение силы за ход (пошагово)
// множитель дальности/скорости для курса ang при ветре wind {ang, str}
export const windMoveMult = (wind, ang) =>
  1 + WIND_STRENGTH * (wind?.str || 0) * Math.cos(ang - (wind?.ang || 0));

