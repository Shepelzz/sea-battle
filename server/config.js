// ─── 🏴‍☠️ КУШ ЗА РАЗБИТУЮ БАЗУ ───────────────────────────────────────────────
// Первая версия правила («половина казны выбитого») и вторая («по его доходу в момент
// гибели») мерили не то. Замер 12 партий: у проигравшего в казне НОЛЬ в 11 случаях из 12 —
// если базу вообще смогли осадить, значит денег у него давно нет, всё ушло на утопленный флот.
// Поэтому куш меряет ПУТЬ игрока за партию: сколько он всего заработал, сколько нанёс урона,
// сколько судов потопил — плюс небольшая доля от того, что всё же осталось в казне (редкий
// случай скупца). Разорить того, кто отыграл большую партию, должно быть заметно ценнее,
// чем добить того, кто слился на двадцатом ходу.
// Ориентиры по тем же 12 партиям: ранний вылет ≈ 180, обычная партия ≈ 450, долгая и
// богатая ≈ 870…980.
export const TRIBUTE_MIN = 100;            // за короткую партию — символически
export const TRIBUTE_MAX = 1000;           // потолок за долгий богатый путь
export const TRIBUTE_W = {
  earned: 0.18,   // всего заработано золота за партию (лут, пираты, клады, дань)
  damage: 0.10,   // нанесённый урон
  sunk: 12,       // потопленные корабли
  purse: 0.05,    // остаток казны (обычно ноль, но скупца награждаем)
};

/** Куш за разрушенную базу игрока victimIdx — по его пути за всю партию. */
export function tributeFor(game, victimIdx) {
  const v = game?.players?.[victimIdx];
  if (!v) return 0;
  const st = v.stats || {};
  const raw = (st.goldCollected || 0) * TRIBUTE_W.earned
    + (st.damageDealt || 0) * TRIBUTE_W.damage
    + (st.shipsSunk || 0) * TRIBUTE_W.sunk
    + (v.gold || 0) * TRIBUTE_W.purse;
  return Math.max(TRIBUTE_MIN, Math.min(TRIBUTE_MAX, Math.round(raw)));
}

