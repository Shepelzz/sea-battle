// Потерявшему всё игроку 6 зол./ход (даже с прежней надбавкой +50% — девять) означало 13 ходов
// копить на шхуну: это не отставание, а ожидание, пока добьют порт. Поэтому надбавка выросла,
// но она НЕ ступенька «есть корабли / нет кораблей», а плавный спад по стоимости флота.
//
// Почему не плоский множитель: при «×3, пока судов нет» покупка первого баркаса (60) роняла
// доход с 18 до 6, а ловил он всего 5 — выгоднее было СИДЕТЬ БЕЗ ФЛОТА. Плавный спад убирает
// эту ловушку: за баркас теряешь 3 зол./ход, а он приносит 5.
//   пусто → 15 · баркас (60) → 13 · шхуна (110) → 11 · от брига (220) и дороже → 6
export const PORT_POOR_MULT = 2.5;    // во сколько раз щедрее порт у игрока БЕЗ единого судна
export const PORT_POOR_FLEET = 220;   // стоимость флота, на которой надбавка сходит на нет (цена брига)
// суммарная цена живого флота игрока — мера того, насколько он отстал
export const fleetValue = (game, pIdx) =>
  (game.ships || []).reduce((sum, s) => sum + (s.owner === pIdx ? (SHIP_TYPES[s.type]?.price || 0) : 0), 0);
// доход порта игрока с учётом поддержки
export function portIncome(game, pIdx) {
  const poor = Math.max(0, 1 - fleetValue(game, pIdx) / PORT_POOR_FLEET); // 1 — гол как сокол, 0 — флот в порядке
  const mult = hasPerk(game, pIdx, 'market') ? MARKET_INCOME_MULT : 1;    // 📈 «торговый ряд»
  return Math.round(PORT_INCOME * (1 + (PORT_POOR_MULT - 1) * poor) * mult);
}
