// ─── ⛵ КОНВОЙ: ход строем (несколько судов одним жестом) ─────────────────────
// Когда бой уехал в центр карты, подгонять подкрепление по одному — долго и муторно.
// Конвой: выбираешь флагман, цепляешь к нему соседей и ведёшь строй ОДНИМ жестом —
// все повторяют смещение флагмана, строй сохраняется. Три ограничения держат его честным:
//   • строй идёт по САМОМУ МЕДЛЕННОМУ (линкор в конвое режет дальность всем);
//   • конвой не собрать в боевом контакте — эскадрой от боя не удрать (convoyContact);
//   • собрать его можно только из соседей флагмана (CONVOY_PICK_MULT);
//   • флагман — НЕ МЛАДШЕ ведомых (shipRank). Иначе рыбацкий баркас, у которого самый большой
//     ход (180), а значит и самый широкий радиус набора, таскал бы за собой фрегаты и линкоры.
export const CONVOY_MAX = 3;        // судов в строю, включая флагман
export const CONVOY_PICK_MULT = 1;  // радиус набора соседей = move флагмана × это
// Цена строя в манёврах хода: ОДИН манёвр на весь строй. Это и есть смысл фичи — перебросить
// эскадру через полкарты за ход, а не по одному судну за манёвр. Плата за скорость: строй
// ползёт по самому медленному, не собирается в бою и не умеет стрелять — чистая логистика.
// Боты пользуются им наравне с людьми (см. buildCandidates → 'convoy'), так что перевеса
// у живого игрока нет. Вернуть «строй = обычные ходы» — поставь (n) => n.
export const convoyCost = (n) => 1;
// цена по размеру строя для клиента (индекс = судов в строю; 0/1 — строя нет)
export const convoyCosts = () => Array.from({ length: CONVOY_MAX + 1 }, (_, n) => (n < 2 ? 0 : convoyCost(n)));

